"""Create a simple updatable Core ML classifier.

This follows the pattern from Apple's Core ML Tools guide
“Updatable Neural Network Classifier on MNIST” but adapts it for:
  - 10 float features as input
  - 4 output classes
  - a single dense layer + softmax

Run this file directly to produce `assets/devOps/UpdatableClassifier.mlmodel`.
"""

from __future__ import annotations

# コマンドライン引数解析用
import argparse
# 環境変数設定用
import os
# JSONデータの読み書き用
import json
from pathlib import Path
from typing import Iterable, List, Sequence

# Core MLモデル構築用ライブラリ
import coremltools as ct
# 数値計算用ライブラリ
import numpy as np
from coremltools.models import datatypes
from coremltools.models.neural_network import AdamParams, NeuralNetworkBuilder


# デフォルトのクラスラベル（4クラス分類用）
DEFAULT_CLASSES: List[str] = [f"class_{i}" for i in range(4)]


def _build_builder(
    feature_dim: int,
    class_labels: Sequence[str],
    input_name: str = "features",
    logits_name: str = "dense",
    prob_name: str = "classProbability",
) -> NeuralNetworkBuilder:
    """Create the NeuralNetworkBuilder with a single trainable dense layer."""
    # 入力特徴量の定義（feature_dim次元の配列）
    input_features = [(input_name, datatypes.Array(feature_dim))]
    # 出力確率の定義（クラス数分の配列）
    output_features = [(prob_name, datatypes.Array(len(class_labels)))]
    # use_float_arraytype -> float32 throughout (smaller & matches most mobile uses)
    # 分類器モードでニューラルネットワークビルダーを作成
    builder = NeuralNetworkBuilder(
        input_features,
        output_features,
        mode="classifier",
        use_float_arraytype=True,
    )

    # Initialize weights with small random values to avoid training instabilities.
    # 重み行列を小さいランダム値で初期化（クラス数 × 特徴量次元）
    weight = (0.01 * np.random.randn(len(class_labels), feature_dim)).astype(np.float32)
    # バイアスベクトルをゼロで初期化
    bias = np.zeros(len(class_labels), dtype=np.float32)

    # 全結合層（内積層）を追加
    builder.add_inner_product(
        name=logits_name,
        input_name=input_name,
        output_name=logits_name,
        W=weight,
        b=bias,
        input_channels=feature_dim,
        output_channels=len(class_labels),
        has_bias=True,
    )
    # ソフトマックス層を追加して確率分布に変換
    builder.add_softmax(
        name="softmax",
        input_name=logits_name,
        output_name=prob_name,
    )
    # クラスラベルを設定
    builder.set_class_labels(class_labels)
    # 予測クラス名を設定
    builder.spec.description.predictedFeatureName = "classLabel"
    # 予測確率名を設定
    builder.spec.description.predictedProbabilitiesName = prob_name
    return builder


def make_updatable_classifier(
    feature_dim: int = 10,
    class_labels: Iterable[str] = DEFAULT_CLASSES,
    output_path: Path | str = Path(__file__).with_name("UpdatableClassifier.mlmodel"),
    epochs: int = 10,
    batch_size: int = 16,
    learning_rate: float = 1e-3,
) -> ct.models.MLModel:
    """Build and save an updatable Core ML classifier."""
    # クラスラベルをリストに変換
    class_labels = list(class_labels)
    # クラス数が4であることを確認
    if len(class_labels) != 4:
        raise ValueError("Expected exactly 4 class labels.")

    # ニューラルネットワークビルダーを作成
    builder = _build_builder(feature_dim=feature_dim, class_labels=class_labels)

    # Mark the dense layer as updatable.
    # 全結合層を更新可能としてマーク
    builder.make_updatable(["dense"])

    # Add loss; target name will be auto-generated as f\"{prob_name}_true\".
    # カテゴリカル交差エントロピー損失を設定
    builder.set_categorical_cross_entropy_loss(name="lossLayer", input="classProbability")

    # Optimizer & training config (mirrors the doc example using Adam).
    # Adamオプティマイザーを設定（学習率、バッチサイズ、ハイパーパラメータ）
    builder.set_adam_optimizer(
        AdamParams(lr=learning_rate, batch=batch_size, beta1=0.9, beta2=0.999, eps=1e-8)
    )
    # エポック数を設定
    builder.set_epochs(epochs)
    # データシャッフルを有効化
    builder.set_shuffle(1)

    # モデル仕様を取得
    spec = builder.spec

    # Optional: enrich metadata for easier debugging downstream.
    # メタデータを設定（説明、作成者、ライセンス）
    spec.description.metadata.shortDescription = (
        "Updatable 4-class classifier over 10 float features."
    )
    spec.description.metadata.author = "Generated by assets/devOps/model.py"
    spec.description.metadata.license = "For internal use"

    # Ensure a writable tmp dir for Core ML runtime (helps avoid predict() warnings)
    # 一時ディレクトリを設定（Core MLランタイム用）
    os.environ.setdefault("TMPDIR", "/tmp")
    # MLModelオブジェクトを作成
    model = ct.models.MLModel(spec)
    # 出力パスをPathオブジェクトに変換
    output_path = Path(output_path)
    # モデルをファイルに保存
    model.save(output_path)
    return model


def demo_prediction(model_path: Path | str = Path(__file__).with_name("UpdatableClassifier.mlmodel")) -> None:
    """Run a single random inference to sanity-check the model wiring."""
    # パスをPathオブジェクトに変換
    model_path = Path(model_path)
    # モデルファイルの存在確認
    if not model_path.exists():
        raise FileNotFoundError(f"{model_path} not found. Run the builder first.")

    # モデルを読み込み（文字列パスに変換）
    model = ct.models.MLModel(str(model_path))
    # ランダムな10次元の特徴量サンプルを生成
    sample = {"features": np.random.rand(10).astype(np.float32)}
    # 予測を実行
    result = model.predict(sample)
    # 結果を出力
    print("Input features:", sample["features"])
    print("Predicted class:", result["classLabel"])
    print("Probabilities:", result["classProbability"])


def write_demo_dataset(
    path: Path | str = Path(__file__).with_name("demo_dataset.json"),
    samples_per_class: int = 25,
) -> Path:
    """Create a tiny synthetic dataset useful for MLUpdateTask demos.

    Each class k is centered near unit vector e_k to make training easy.
    Saved as a JSON array of {features: [...], classLabel: "..."} dicts.
    """
    # パスをPathオブジェクトに変換
    path = Path(path)
    # 再現可能な乱数生成器を初期化（シード42）
    rng = np.random.default_rng(42)
    # 全データ行を格納するリスト
    all_rows = []
    # 4クラス分のデータを生成
    for k in range(4):
        # 各クラスの中心点を設定（k番目の次元を1.0に）
        center = np.zeros(10, dtype=np.float32)
        center[k % 10] = 1.0  # spread first 4 dims
        # クラスごとに指定数のサンプルを生成
        for _ in range(samples_per_class):
            # ノイズを追加（標準偏差0.1の正規分布）
            noise = rng.normal(scale=0.1, size=10).astype(np.float32)
            # 中心点にノイズを加えた特徴量を生成
            feat = center + noise
            # データ行を追加
            all_rows.append(
                {
                    "features": feat.tolist(),
                    "classLabel": f"class_{k}",
                }
            )
    # JSON形式でファイルに保存
    path.write_text(json.dumps(all_rows, indent=2))
    return path


def main() -> None:
    # コマンドライン引数パーサーを作成
    parser = argparse.ArgumentParser(description="Build updatable Core ML classifier.")
    # デモ予測実行オプションを追加
    parser.add_argument("--demo", action="store_true", help="Run a quick random inference after build.")
    # デモデータセット生成オプションを追加
    parser.add_argument(
        "--write-demo-data",
        action="store_true",
        help="Emit a small synthetic dataset for on-device update testing.",
    )
    # 引数を解析
    args = parser.parse_args()

    # 更新可能な分類器モデルを構築して保存
    make_updatable_classifier()
    print("Saved updatable model to UpdatableClassifier.mlmodel")

    # デモオプションが指定された場合、予測を実行
    if args.demo:
        try:
            demo_prediction()
        except Exception as exc:  # noqa: BLE001
            print(f"[demo skipped] {exc}")

    # デモデータセット生成オプションが指定された場合、データセットを生成
    if args.write_demo_data:
        path = write_demo_dataset()
        print(f"Wrote synthetic training data to {path}")


if __name__ == "__main__":
    main()
